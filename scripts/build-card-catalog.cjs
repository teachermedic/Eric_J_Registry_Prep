// Regenerate after editing either card bank: node scripts/build-card-catalog.cjs
const fs=require('node:fs'),vm=require('node:vm'),path=require('node:path');
const root=path.join(__dirname,'..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const clinical=vm.runInNewContext(read('flashcard_data.js')+';quizData');
const terms=vm.runInNewContext(read('terminology-data.js')+';TERM_DECKS');
const groups={
 'EMS Operations':['EMS Systems','Legal','Safety','Communications','Lifting','Wellness'],
 'Trauma':['Trauma','MOI','Bleeding','Chest','Abdominal','Ortho','Head/Spine','Environmental','Soft-Tissue','Physics','Shock','Face/Neck'],
 'Pathophysiology':['Patho','Pathophysiology'],'Pediatrics':['Pediatrics','Neonatal'],'OB/GYN':['Obstetrics','OBPeds','Gynecology'],'Terminology':['Terminology']
};
const cards=clinical.filter(c=>['single','open-review','multiple','text'].includes(c.type)).map(c=>{
 const deck=Object.keys(groups).find(d=>groups[d].includes(c.category))||'Medical';
 return {id:JSON.stringify(['clinical',c.category||'unknown',c.q]),kind:'clinical',deck,front:c.q,legacy:(c.category||'unknown')+'|'+c.q};
}).concat(terms.map(c=>({id:JSON.stringify(['terms',c.cat,c.term]),kind:'terms',deck:c.cat,front:c.term,legacy:c.cat+'|'+c.term})));
const unique=[...new Map(cards.map(c=>[c.id,c])).values()];
fs.writeFileSync(path.join(root,'card-catalog.js'),'// Generated by scripts/build-card-catalog.cjs; do not edit by hand.\nwindow.FIELD_NOTE_CARDS = '+JSON.stringify(unique,null,2)+';\n');
console.log('Catalog:',unique.length,'unique cards');
